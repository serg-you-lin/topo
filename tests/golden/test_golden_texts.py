"""
test_golden_texts.py
--------------------
Regression on the reading of texts: compares `topo_dxf.load_dxf(...).texts`
(`Text`) with the golden in tests/data/golden_faces/texts/.

Golden generated by tests/tools/generate_golden_texts.py — to be regenerated
only after checking by hand that the reading is right, never to make a test
pass. They lost the keys of the entity type and of the source's assertions;
every other entry was proved equal to before.

One test per fixture, generated by the factory at the bottom of the file.
"""

import json
import unittest
from pathlib import Path


import topo
import topo_dxf
from topo.tools.anchor import anchor_texts
from tests.paths import DATA

EXAMPLES_DIR = DATA
GOLDEN_DIR = EXAMPLES_DIR / "golden_faces" / "texts"
_SOURCE_DIRS = [EXAMPLES_DIR, EXAMPLES_DIR / "golden_faces"]


def _find_source(name: str):
    for d in _SOURCE_DIRS:
        p = d / name
        if p.exists():
            return p
    return None


TOL_POS = 0.05      # mm — tolerance on the anchor position
TOL_VALUE = 0.01    # mm — tolerance on the measured value


def _golden_files():
    if not GOLDEN_DIR.exists():
        return []
    return sorted(GOLDEN_DIR.glob("*.json"))


def _rendered_counts(r) -> dict:
    return {"strokes": len(r.strokes), "fills": len(r.fills), "texts": len(r.texts)}


def text_dict(t) -> dict:
    """The golden of a `Text`: height and rotation only for a string with no image
    (with an image the writer rewrites that)."""
    d = {
        "position": [round(t.position[0], 3), round(t.position[1], 3)],
        "halign": t.halign,
        "valign": t.valign,
        "text": t.text,
        "cluster_ref": t.cluster_ref,
    }
    if t.rendered.is_empty():
        d["height"] = round(t.height, 3)
        d["rotation"] = round(t.rotation, 3)
    d["rendered"] = _rendered_counts(t.rendered)
    if t.measures is not None:
        # what it measures, with the source's points
        d["measures"] = {k: _rounded(v) for k, v in vars(t.measures).items()}
        d["measures"]["kind"] = type(t.measures).__name__
    return d


def _rounded(v):
    if isinstance(v, float):
        return round(v, 3)
    if isinstance(v, tuple):
        return [_rounded(x) for x in v]
    return v


def sort_key(entry: dict):
    return (entry["position"][0], entry["position"][1], entry["text"])


def _make_test(path: Path):
    def test(self):
        golden = json.loads(path.read_text(encoding="utf-8"))
        dxf_path = _find_source(golden["source_file"])
        if dxf_path is None:
            self.skipTest(golden["source_file"])
        doc = topo_dxf.load_dxf(
            dxf_path, explode_inserts=True, flatten_z=True, verbose=False
        )
        result = topo.heal(doc).faces()
        anchor_texts(result)
        texts = result.texts if result.texts else doc.texts
        actual = sorted((text_dict(t) for t in texts), key=sort_key)
        expected = golden["texts"]

        if "cluster_count" in golden:
            self.assertEqual(
                len(result.clusters), golden["cluster_count"],
                msg=f"{golden['source_file']}: number of parts",
            )
        self.assertEqual(len(actual), golden["text_count"],
                         msg=f"{golden['source_file']}: numero texts")
        for i, (act, exp) in enumerate(zip(actual, expected)):
            ctx = f"{golden['source_file']} testo[{i}]"
            self.assertEqual(act.keys(), exp.keys(), msg=f"{ctx}: fields")
            for key in ("halign", "valign", "text", "cluster_ref", "rendered"):
                self.assertEqual(act[key], exp[key], msg=f"{ctx}: {key}")
            for key in ("height", "rotation"):
                if key in exp:
                    self.assertAlmostEqual(act[key], exp[key], delta=TOL_VALUE, msg=f"{ctx}: {key}")
            self.assertAlmostEqual(act["position"][0], exp["position"][0], delta=TOL_POS, msg=f"{ctx}: x")
            self.assertAlmostEqual(act["position"][1], exp["position"][1], delta=TOL_POS, msg=f"{ctx}: y")

    return test


class TestGoldenTexts(unittest.TestCase):
    pass


for _golden in _golden_files():
    setattr(TestGoldenTexts, f"test_{_golden.stem}", _make_test(_golden))


class TestGoldenTextsSetup(unittest.TestCase):
    def test_golden_dir_populated(self):
        self.assertGreater(len(_golden_files()), 0, "no golden for the texts")


if __name__ == "__main__":
    unittest.main()
